/**
 * Continuous replication of alineod's SQLite files with Litestream (durability-roadmap M4, 4.2).
 *
 * Litestream streams each database's WAL to the bucket about once a second, so a lost disk costs
 * seconds of events and not the time since the last backup. It runs beside alineod as its own
 * process. alineod does not call it. This file only writes its config and builds its restore
 * command, so both are testable without the binary.
 *
 * Credentials are not written to the config. Litestream reads `LITESTREAM_ACCESS_KEY_ID` and
 * `LITESTREAM_SECRET_ACCESS_KEY` from its environment, so the config file holds no secrets and
 * can be kept in the open.
 *
 * Litestream replicates one writer. Two alineod processes on the same database are already refused
 * by the instance lease, so this adds no new limit. It is a single-node tool by nature.
 */
import { basename } from "node:path";
import { offboxFolder, type OffboxConfig } from "./offbox";

/** A YAML double-quoted scalar. JSON string syntax is valid YAML, so no extra escaping is needed. */
const q = (value: string): string => JSON.stringify(value);

/** The replica path inside the bucket for one database file. */
export function replicaPath(cfg: Pick<OffboxConfig, "prefix" | "instanceId">, dbPath: string) {
  return `${offboxFolder(cfg, "db")}/${basename(dbPath)}`;
}

/**
 * `litestream.yml` for the given database files. Two files with the same name would share one
 * replica path and overwrite each other, so that is refused.
 */
export function litestreamConfig(dbPaths: readonly string[], cfg: OffboxConfig): string {
  const names = new Set<string>();
  for (const p of dbPaths) {
    const name = basename(p).toLowerCase();
    if (names.has(name)) {
      throw new Error(
        `cannot replicate: two databases share the file name "${basename(p)}", so they would ` +
          `share one replica path. Give them different file names.`,
      );
    }
    names.add(name);
  }
  const lines = [
    "# Generated by apps/alineod/scripts/litestream-config.ts. Do not edit: regenerate it.",
    "# Credentials come from LITESTREAM_ACCESS_KEY_ID and LITESTREAM_SECRET_ACCESS_KEY.",
    "dbs:",
  ];
  for (const dbPath of dbPaths) {
    lines.push(
      `  - path: ${q(dbPath)}`,
      "    replicas:",
      "      - type: s3",
      `        bucket: ${q(cfg.bucket)}`,
      `        path: ${q(replicaPath(cfg, dbPath))}`,
      ...(cfg.endpoint
        ? [`        endpoint: ${q(cfg.endpoint)}`, "        force-path-style: true"]
        : []),
      ...(cfg.region ? [`        region: ${q(cfg.region)}`] : []),
      "        sync-interval: 1s",
    );
  }
  return `${lines.join("\n")}\n`;
}

/**
 * Arguments for `litestream restore` of one database to its original path. It skips a database
 * that already exists and one that has no replica, so running it twice, or on a box where one
 * file was never replicated, is safe.
 */
export function litestreamRestoreArgs(configPath: string, dbPath: string): string[] {
  return [
    "restore",
    "-config",
    configPath,
    "-if-db-not-exists",
    "-if-replica-exists",
    "-o",
    dbPath,
    dbPath,
  ];
}
